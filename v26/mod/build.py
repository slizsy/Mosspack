def read(*p, mode='r'):
    with open(os.path.join(*p), mode, **({} if 'b' in mode else {'encoding': 'utf-8'})) as f:
        return f.read()


def write(name, data):
    path = os.path.join(PARTS, name)
    with open(path, 'wb' if isinstance(data, bytes) else 'w', **({} if isinstance(data, bytes) else {'encoding': 'utf-8'})) as f:
        f.write(data)
    return path


def patch(text, pairs, what):
    for old, new in pairs:
        n = text.count(old)
        if n != 1:
            sys.exit(f'{what}: expected 1 match of {old[:70]!r}, found {n}')
        text = text.replace(old, new)
    return text


def data_url(path):
    return 'data:image/png;base64,' + base64.b64encode(read(path, mode='rb')).decode()


