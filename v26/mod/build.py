# the other official capes, for js/seed-capes.js: 22x17 cape area as 23x17 BGR (the game's custom-cape format)
def cape_data(path):
    px = Image.open(path).convert('RGBA').load()
    out = bytearray(23 * 17 * 3)
    for y in range(17):
        for x in range(22):
            r, g, b, _ = px[x, y]
            out[(y * 23 + x) * 3:(y * 23 + x) * 3 + 3] = bytes((b, g, r))
    return base64.b64encode(bytes(out)).decode()


