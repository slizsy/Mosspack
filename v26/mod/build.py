def pick(value, above, choices):               # value (local get bytes) -> color by thresholds (compare op per entry)
    out = b''
    for (threshold, compare), color in zip(above, choices):
        out += value + threshold + compare + b'\x04\x7f' + i32_const(color) + b'\x05'
    return out + i32_const(choices[-1]) + b'\x0b' * len(above)


fps, tps = b'\x20\x03', b'\x20\x0f'                                       # locals 3 (i32) and 15 (f64) in $47261
